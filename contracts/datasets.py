"""Frozen objective, translation-table and manifest schemas (§5.2 interface freeze).

Spec sources: objectives and oracles (§3.1, §3.4: an objective is base query,
goal O1 to O4, per-trial marker, oracle), the pre-translated table of base
objectives (§3.4: Arabic, French, Spanish; built once, spot-checked and
hash-committed), dataset manifests with hashes (§2.3, §2.4, §2.7: committed
hash of the sorted test-set IDs; `data/manifests/` is tracked), and the active
canary and PII manifest passed in-process to L4 (PS-2, PS-3, D-PII, IP-5:
egress verdicts are keyed by manifest ID).

Identifiers (`objective_id`, document ids, item ids) exclude `|`, because the
PS-3 HMAC messages join fields with `|` (`f"pii|{objective_id}|{entity_type}"`);
an id containing `|` could make two different (id, field) pairs derive the
same secret [Project Decision, extends PS-3].

Template slots are the literal strings `{payload}` and `{marker}`, filled by
plain string replacement (never `str.format`), so other braces in a template
are safe. The per-trial marker is generated by the harness per trial and is
never stored in an objective file.

Imports only stdlib, pydantic and `contracts`.
"""

from __future__ import annotations

import unicodedata
from typing import Annotated, Literal

from pydantic import BaseModel, ConfigDict, Field, StringConstraints, field_validator, model_validator

from contracts.hashing import canonical_hash
from contracts.modes import DerivationKind

FORMAT_VERSION = 1
PAYLOAD_SLOT = "{payload}"
MARKER_SLOT = "{marker}"

Identifier = Annotated[str, StringConstraints(pattern=r"^[A-Za-z0-9][A-Za-z0-9_.:-]{0,127}$")]
Sha256Hex = Annotated[str, StringConstraints(pattern=r"^[0-9a-f]{64}$")]
NonEmptyStr = Annotated[str, StringConstraints(min_length=1)]

Goal = Literal["O1", "O2", "O3", "O4"]
OracleName = Literal["canary_or_leak_similarity", "planted_pii_unmasked", "marker_without_refusal", "marker_emitted"]
ORACLE_BY_GOAL: dict[str, str] = {
    "O1": "canary_or_leak_similarity",  # SG4 system-prompt leak
    "O2": "planted_pii_unmasked",  # SG3 PII exfiltration
    "O3": "marker_without_refusal",  # SG1 policy-violating compliance
    "O4": "marker_emitted",  # SG2 indirect injection
}
Split = Literal["train", "val", "test"]
AttackFamily = Literal["template", "persuade", "logic"]
TranslationLanguage = Literal["ar", "fr", "es"]
TRANSLATION_LANGUAGES: tuple[str, ...] = ("ar", "fr", "es")
PiiEntityType = Literal["EMAIL_ADDRESS", "PHONE_NUMBER", "CREDIT_CARD", "US_SSN", "IBAN_CODE"]
PII_ENTITY_TYPES: tuple[str, ...] = ("EMAIL_ADDRESS", "PHONE_NUMBER", "CREDIT_CARD", "US_SSN", "IBAN_CODE")

# Format (Cf) characters allowed in curated multilingual text (Arabic, Persian).
# Kept identical to `scripts/ps5_lint.py` CURATED_ALLOWED_FORMAT_CHARS (tested).
CURATED_ALLOWED_FORMAT_CHARS = frozenset({"\u200c", "\u200e", "\u200f", "\u061c"})

_FROZEN = ConfigDict(frozen=True, extra="forbid")


def base_query_sha256(base_query: str) -> str:
    """Hash that ties a translation entry to the exact English base query it translates."""
    return canonical_hash({"base_query": base_query})


def _slot_count(text: str, slot: str) -> int:
    return text.count(slot)


# Objectives (§3.1, §3.4)


class ContextDocumentTemplate(BaseModel):
    """The retrieved document an O4 payload is planted in (CA-1 `{id, source, text}`)."""

    model_config = _FROZEN

    id: Identifier
    source: NonEmptyStr
    text_template: NonEmptyStr


class ObjectiveRecord(BaseModel):
    """One red-team objective. Rendering puts the operator-mutated base query in `{payload}`."""

    model_config = _FROZEN

    objective_id: Identifier
    goal: Goal
    oracle: OracleName
    base_query_id: Identifier
    base_query: NonEmptyStr
    split: Split
    task_template: NonEmptyStr
    context_template: ContextDocumentTemplate | None = None

    @model_validator(mode="after")
    def _goal_template_and_oracle_agree(self) -> ObjectiveRecord:
        if self.oracle != ORACLE_BY_GOAL[self.goal]:
            raise ValueError(f"{self.goal} uses oracle {ORACLE_BY_GOAL[self.goal]!r}, got {self.oracle!r}")
        task = self.task_template
        if self.goal == "O4":
            if self.context_template is None:
                raise ValueError("O4 plants its payload in aegis_context and requires context_template")
            doc = self.context_template.text_template
            if _slot_count(doc, PAYLOAD_SLOT) != 1 or _slot_count(doc, MARKER_SLOT) != 1:
                raise ValueError("O4 context_template.text_template needs exactly one {payload} and one {marker}")
            if PAYLOAD_SLOT in task or MARKER_SLOT in task:
                raise ValueError("O4 task_template is the benign user question and holds no slots")
            return self
        if self.context_template is not None:
            raise ValueError(f"{self.goal} sends only user_prompt; context_template must be None")
        if _slot_count(task, PAYLOAD_SLOT) != 1:
            raise ValueError("task_template needs exactly one {payload}")
        markers = _slot_count(task, MARKER_SLOT)
        if self.goal == "O3" and markers != 1:
            raise ValueError("O3 task_template carries the marker instruction: exactly one {marker}")
        if self.goal in ("O1", "O2") and markers:
            raise ValueError(f"{self.goal} has no per-trial marker; task_template must not contain {{marker}}")
        return self


class ObjectiveFile(BaseModel):
    """An objective file (R4 hands it to the attacker CLI and the harness)."""

    model_config = _FROZEN

    format_version: Literal[1] = FORMAT_VERSION
    objectives: Annotated[tuple[ObjectiveRecord, ...], Field(min_length=1)]

    @model_validator(mode="after")
    def _unique_ids(self) -> ObjectiveFile:
        ids = [o.objective_id for o in self.objectives]
        if len(set(ids)) != len(ids):
            raise ValueError("objective_id values must be unique")
        return self

    @property
    def content_hash(self) -> str:
        return canonical_hash(self)

    def get(self, objective_id: str) -> ObjectiveRecord:
        for objective in self.objectives:
            if objective.objective_id == objective_id:
                return objective
        raise KeyError(objective_id)


# Translation table (§3.4 translate operator)


def _check_curated_text(text: str) -> str:
    for ch in text:
        if (ord(ch) < 0x20 and ch != "\n") or ord(ch) == 0x7F:
            raise ValueError(f"translation text contains control character U+{ord(ch):04X}")
        if unicodedata.category(ch) == "Cf" and ch not in CURATED_ALLOWED_FORMAT_CHARS:
            raise ValueError(f"translation text contains disallowed format character U+{ord(ch):04X}")
    return text


class TranslationEntry(BaseModel):
    """One pre-translated base objective. The marker instruction stays English, so no slots appear here."""

    model_config = _FROZEN

    objective_id: Identifier
    language: TranslationLanguage
    source_sha256: Sha256Hex
    text: NonEmptyStr
    spot_checked: bool = False

    @field_validator("text")
    @classmethod
    def _text_is_clean(cls, value: str) -> str:
        if PAYLOAD_SLOT in value or MARKER_SLOT in value:
            raise ValueError("translated text must not contain {payload} or {marker}")
        return _check_curated_text(value)


class TranslationTable(BaseModel):
    """The hash-committed translation table (lives in tracked `data/translations/`)."""

    model_config = _FROZEN

    format_version: Literal[1] = FORMAT_VERSION
    entries: Annotated[tuple[TranslationEntry, ...], Field(min_length=1)]

    @model_validator(mode="after")
    def _unique_pairs(self) -> TranslationTable:
        pairs = [(e.objective_id, e.language) for e in self.entries]
        if len(set(pairs)) != len(pairs):
            raise ValueError("each (objective_id, language) pair must appear once")
        return self

    @property
    def table_hash(self) -> str:
        return canonical_hash(self)

    def lookup(self, objective_id: str, language: str) -> str:
        for entry in self.entries:
            if entry.objective_id == objective_id and entry.language == language:
                return entry.text
        raise KeyError((objective_id, language))

    def check_against(self, objectives: ObjectiveFile) -> None:
        """Raise ValueError unless every entry names a known objective and matches its base query hash."""
        for entry in self.entries:
            try:
                objective = objectives.get(entry.objective_id)
            except KeyError:
                raise ValueError(f"translation for unknown objective {entry.objective_id!r}") from None
            if entry.source_sha256 != base_query_sha256(objective.base_query):
                raise ValueError(
                    f"translation {entry.objective_id}/{entry.language} is stale: source_sha256 does not "
                    "match the objective's base query"
                )


# Dataset manifests (§2.3, §2.4, §2.7; tracked in data/manifests/)


SplitScheme = Literal["S1", "S2", "S3", "none"]
Partition = Literal["train", "val", "test", "adaptive", "all"]


class DatasetManifest(BaseModel):
    """Sorted item IDs of one dataset partition plus their hash (hash-committed before tuning)."""

    model_config = _FROZEN

    format_version: Literal[1] = FORMAT_VERSION
    dataset: Identifier
    source: NonEmptyStr
    split_scheme: SplitScheme
    partition: Partition
    fold: AttackFamily | None = None
    seed: int | None = None
    item_ids: Annotated[tuple[Identifier, ...], Field(min_length=1)]
    ids_sha256: Sha256Hex

    @model_validator(mode="after")
    def _ids_sorted_unique_and_hashed(self) -> DatasetManifest:
        if list(self.item_ids) != sorted(set(self.item_ids)):
            raise ValueError("item_ids must be sorted and unique")
        if self.ids_sha256 != canonical_hash(list(self.item_ids)):
            raise ValueError("ids_sha256 does not match canonical_hash(sorted item_ids)")
        scheme, part = self.split_scheme, self.partition
        if scheme in ("S1", "S2") and part not in ("train", "val", "test"):
            raise ValueError(f"{scheme} partitions are train, val, test")
        if scheme == "S3" and part != "adaptive":
            raise ValueError("S3 is the adaptive set; partition must be 'adaptive'")
        if scheme == "none" and part != "all":
            raise ValueError("an unsplit dataset uses partition 'all'")
        if (scheme == "S2") != (self.fold is not None):
            raise ValueError("fold (the held-out family) is required for S2 and only for S2")
        if scheme in ("S1", "S2") and self.seed is None:
            raise ValueError(f"{scheme} splits are seeded; seed is required")
        return self

    @classmethod
    def from_item_ids(cls, *, item_ids: list[str] | tuple[str, ...], **fields: object) -> DatasetManifest:
        ordered = tuple(sorted(set(item_ids)))
        if len(ordered) != len(item_ids):
            raise ValueError("item_ids contain duplicates")
        return cls(item_ids=ordered, ids_sha256=canonical_hash(list(ordered)), **fields)

    @property
    def item_count(self) -> int:
        return len(self.item_ids)

    @property
    def manifest_id(self) -> str:
        return canonical_hash(self)


# Active canary and PII manifest (PS-2, PS-3, D-PII, IP-5); in-process only, never written to disk.


class PlantedPII(BaseModel):
    model_config = _FROZEN

    entity_type: PiiEntityType
    value: Annotated[NonEmptyStr, Field(repr=False)]


class CanaryPIIManifest(BaseModel):
    """The secrets planted in one gateway-built system prompt, handed in-process to L4.

    `manifest_id` covers the objective, the canary, the planted values and the
    system-prompt hash, and nothing about the mode, so deterministic modes
    (eval, shadow tiers) that derive the same secrets share one manifest ID and
    egress-verdict cache entries (IP-5, PS-3). Secret fields are hidden from repr.
    """

    model_config = _FROZEN

    objective_id: Identifier
    derivation: DerivationKind
    canary: Annotated[NonEmptyStr, Field(repr=False)]
    planted_pii: tuple[PlantedPII, ...]
    system_prompt_sha256: Sha256Hex

    @model_validator(mode="after")
    def _all_entity_types_once_in_order(self) -> CanaryPIIManifest:
        types = tuple(p.entity_type for p in self.planted_pii)
        if types != tuple(sorted(PII_ENTITY_TYPES)):
            raise ValueError(f"planted_pii must hold each of {sorted(PII_ENTITY_TYPES)} once, sorted")
        return self

    @property
    def manifest_id(self) -> str:
        return canonical_hash(
            {
                "manifest": "canary_pii",
                "objective_id": self.objective_id,
                "canary": self.canary,
                "planted_pii": [[p.entity_type, p.value] for p in self.planted_pii],
                "system_prompt_sha256": self.system_prompt_sha256,
            }
        )

    def pii_value(self, entity_type: str) -> str:
        for item in self.planted_pii:
            if item.entity_type == entity_type:
                return item.value
        raise KeyError(entity_type)
